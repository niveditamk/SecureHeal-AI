"""Repair generator — LLM-based candidate patch generation with constraint validation."""

from __future__ import annotations

import difflib
import logging

logger = logging.getLogger("secureheal.repair")


class RepairGenerator:
    """Generates candidate patches and validates them against constraints."""

    def generate_patch(
        self,
        root_cause: dict,
        context: dict,
        constraints: list[str],
        knowledge: list[dict] | None = None,
    ) -> list[dict]:
        """Generate 1-3 candidate patches using the repair agent.

        This is a utility wrapper — the actual LLM call happens in RepairGenerationAgent.
        This class provides constraint validation and diff formatting.
        """
        patches = []
        # Patches are generated by RepairGenerationAgent; this helper validates them
        return patches

    def apply_constraints(self, patch: dict, constraints: list[str]) -> dict:
        """Validate a patch against security constraints.

        Returns the patch dict enriched with constraint_results.
        """
        results = []
        for constraint in constraints:
            # Heuristic checks based on constraint keywords
            passed = True
            reason = "Assumed compliant"

            patched_code = patch.get("patched_code", "").lower()
            original_code = patch.get("original_code", "").lower()

            if "parameterized" in constraint.lower() and "?" not in patched_code and "%s" not in patched_code:
                if "execute" in patched_code and ("+" in patched_code or "format" in patched_code or "f'" in patched_code):
                    passed = False
                    reason = "Patched code may still concatenate user input into SQL"

            if "escape" in constraint.lower() or "encode" in constraint.lower():
                if "html.escape" not in patched_code and "escape(" not in patched_code and "Encode." not in patch.get("patched_code", ""):
                    if "<script" in original_code.lower() or "xss" in str(patch).lower():
                        passed = False
                        reason = "Output encoding/escaping not found in patched code"

            if "environment variable" in constraint.lower():
                if any(kw in patched_code for kw in ["os.environ", "os.getenv", "system.getenv", "dotenv"]):
                    passed = True
                    reason = "Uses environment variables"

            results.append({
                "constraint": constraint,
                "passed": passed,
                "reason": reason,
            })

        patch["constraint_results"] = results
        patch["all_constraints_satisfied"] = all(r["passed"] for r in results)
        return patch

    @staticmethod
    def format_as_diff(original: str, patched: str, file_path: str = "file") -> str:
        """Generate a unified diff between original and patched code."""
        return "".join(
            difflib.unified_diff(
                original.splitlines(keepends=True),
                patched.splitlines(keepends=True),
                fromfile=f"a/{file_path}",
                tofile=f"b/{file_path}",
            )
        )
